import re

from fastapi.testclient import TestClient
from sqlmodel import Session, select

from app.db import get_setting
from app.models import PushSubscription
from tests.conftest import raw_post, register


def _csrf_token(client) -> str:
    resp = client.get("/settings")
    match = re.search(r'name="csrf_token" value="([^"]+)"', resp.text)
    assert match, "no csrf_token found on /settings"
    return match.group(1)


def test_vapid_public_key_requires_login(client):
    resp = client.get("/push/vapid-public-key", follow_redirects=False)
    assert resp.status_code == 303


def test_vapid_public_key_returns_the_configured_key(client, test_engine):
    register(client, "alice@example.com")
    with Session(test_engine) as session:
        expected = get_setting(session, "vapid_public_key")
    assert expected  # generated by init_db()

    resp = client.get("/push/vapid-public-key")
    assert resp.status_code == 200
    assert resp.json() == {"key": expected}


def test_subscribe_creates_a_push_subscription(client, test_engine):
    register(client, "alice@example.com")
    token = _csrf_token(client)

    resp = raw_post(
        client,
        "/push/subscribe",
        json={"endpoint": "https://push.example/abc", "keys": {"p256dh": "p-key", "auth": "a-key"}},
        headers={"X-CSRF-Token": token},
    )
    assert resp.status_code == 200

    with Session(test_engine) as session:
        subs = session.exec(select(PushSubscription)).all()
        assert len(subs) == 1
        assert subs[0].endpoint == "https://push.example/abc"
        assert subs[0].p256dh == "p-key"
        assert subs[0].auth == "a-key"


